import { test, expect } from '@playwright/test';

test('setup, navigation, CRUD, alert disposal, query and persistence', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: '初始化管理员' })).toBeVisible();
  await page.getByLabel('设置本地密码（至少 12 位）').fill('Browser-Test-Passphrase-91');
  await page.getByLabel('确认密码').fill('Browser-Test-Passphrase-91');
  await page.getByRole('button', { name: '创建本地管理员', exact: true }).click();
  await expect(page.getByText('预警处置作战台', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '签收', exact: true }).first().click();
  await expect(page.getByText('预警已签收', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '处置', exact: true }).first().click();
  await page.getByLabel('处置说明').fill('本地回归验证，已人工核实。');
  await page.getByRole('button', { name: '提交处置', exact: true }).click();
  await expect(page.getByText('处置结果已保存', { exact: true })).toBeVisible();
  await page.goto('/#/admin/cameras');
  await page.getByRole('button', { name: '＋ 新增视频点位', exact: true }).click();
  await page.getByLabel('名称', { exact: true }).fill('回归测试摄像头');
  await page.getByLabel('设备编号', { exact: true }).fill('LOCAL-TEST');
  await page.getByLabel('所属辖区', { exact: true }).selectOption('江北区');
  await page.getByRole('dialog').getByLabel('状态', { exact: true }).selectOption('offline');
  await page.getByLabel('经度', { exact: true }).fill('121.51');
  await page.getByLabel('纬度', { exact: true }).fill('29.95');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.getByText('已保存到本地数据库', { exact: true })).toBeVisible();
  await page.getByLabel('搜索名称或点位').fill('回归测试摄像头');
  await page.getByRole('button', { name: '查询', exact: true }).click();
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await expect(page.getByRole('cell', { name: '回归测试摄像头', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  await page.getByRole('dialog').getByLabel('状态', { exact: true }).selectOption('online');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.getByRole('cell', { name: '在线', exact: true })).toBeVisible();
  await page.reload();
  await page.getByLabel('搜索名称或点位').fill('回归测试摄像头');
  await page.getByRole('button', { name: '查询', exact: true }).click();
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await expect(page.getByRole('cell', { name: '在线', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '删除', exact: true }).click();
  await page.getByRole('button', { name: '确认删除', exact: true }).click();
  await expect(page.getByText('暂无记录，可通过新增建立本地数据', { exact: true })).toBeVisible();
  await page.goto('/#/search');
  await page.getByRole('radio', { name: '机动车', exact: true }).check();
  await page.getByLabel('最低置信度 (%)').fill('90');
  await page.getByRole('button', { name: '⌕ 开始检索', exact: true }).click();
  const cards = page.locator('.capture-card');
  await expect(cards.first()).toBeVisible();
  for (const value of await cards.locator('.capture-image>b').allTextContents()) expect(Number(value.replace('%', ''))).toBeGreaterThanOrEqual(90);
  for (const route of ['overview', 'uav', 'police', 'apps', 'archives', 'admin/dashboard', 'admin/dji', 'admin/accounts', 'admin/logs']) {
    await page.goto(`/#/${route}`);
    await expect(page.locator('#content')).not.toContainText('页面加载失败');
    await expect(page.locator('#content .loading')).toHaveCount(0);
  }
  await page.goto('/#/admin/dji');
  await page.getByLabel(/^项目 UUID/).fill('local-browser-project');
  await page.getByRole('button', { name: '保存配置', exact: true }).click();
  await page.reload();
  await expect(page.getByLabel(/^项目 UUID/)).toHaveValue('local-browser-project');
  await page.getByRole('button', { name: '测试连接', exact: true }).click();
  await expect(page.getByText('DJI 适配器未安装，未向设备发送任何指令', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

